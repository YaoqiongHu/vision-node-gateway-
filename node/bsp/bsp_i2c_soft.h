#ifndef BSP_I2C_SOFT_H
#define BSP_I2C_SOFT_H

#include <stdint.h>

/* =============================================================================
 *  bsp_i2c_soft —— 软件 I²C（位翻转）
 *
 *  为什么不用硬件 I2C：
 *    · 从机时钟拉伸（OV7670 不会拉，但 MPU6050 会）要写状态机去处理；
 *    · 总线一旦卡死要复位外设、重配整个 I2C 寄存器组；
 *    · 100 kHz 下位翻转的 CPU 开销可以忽略（一次寄存器读写约 200 µs）。
 *  换来的是"每一根线上的每个电平都是我写出来的"，用逻辑分析仪能一根根对准。
 *
 *  时序：SCL 空闲高、SDA 空闲高（开漏 + 上拉）。
 *        起始 = SCL 高时 SDA 下降；停止 = SCL 高时 SDA 上升。
 *
 *  约定：所有接口传 **7 位地址**（OV7670 = 0x21、MPU6050 = 0x68），
 *        移位和读写位在内部拼，驱动层不碰。
 * ========================================================================== */

/** 引脚配成开漏输出、释放总线。必须在 dwt_init() 之后调用（靠 DWT 做延时）。 */
void bsp_i2c_init(void);

/**
 * 只发"起始 + 地址 + 停止"，用来判断某个地址上有没有器件。
 * @return 1 = 从机在第 9 个时钟拉低了 SDA（应答）；0 = 没有器件
 */
int bsp_i2c_probe(uint8_t addr7);

/**
 * 写 n 个字节（第一个通常是从机寄存器地址）。
 * @return 1 = 从机应答；0 = 无应答（SCCB 允许不应答，不算错误）
 */
int bsp_i2c_write(uint8_t addr7, const uint8_t *buf, uint32_t n);

/**
 * 读 n 个字节。最后一个字节主机发 NACK（I²C 规矩），中间的发 ACK。
 * 注意：OV7670 的 SCCB 只支持"一次读一个寄存器"。
 * @return 1 = 从机应答；0 = 无应答
 */
int bsp_i2c_read(uint8_t addr7, uint8_t *buf, uint32_t n);

/** 扫 0x08–0x77，打印所有应答的地址并返回个数。 */
int bsp_i2c_scan(void);

#endif /* BSP_I2C_SOFT_H */
